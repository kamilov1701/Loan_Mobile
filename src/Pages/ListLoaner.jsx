import React, { useEffect, useState } from "react";
import { ArrowLeft } from "lucide-react";
import { Link } from "react-router-dom";
import { db } from "../firebase";
import { collection, onSnapshot, deleteDoc, doc, query, orderBy } from "firebase/firestore";

import { FaPlusCircle } from "react-icons/fa";
import { FaCircleMinus } from "react-icons/fa6";
import { FaHistory } from "react-icons/fa";
import { IoEyeSharp } from "react-icons/io5";
import { FaPencil } from "react-icons/fa6";
import { RiDeleteBinLine } from "react-icons/ri";
import { FaFileExcel } from "react-icons/fa";

import * as XLSX from "xlsx";

function ListLoaner() {
  const [loaners, setLoaners] = useState([]);
  const [selectedPhoto, setSelectedPhoto] = useState(null);
  const [search, setSearch] = useState("");

  useEffect(() => {
    const q = query(collection(db, "loaners"), orderBy("createdAt", "desc"));

    const unsubscribe = onSnapshot(q, (snapshot) => {
      const data = snapshot.docs.map((doc) => ({
        id: doc.id,
        ...doc.data(),
      }));

      // show only ACTIVE loaners
      const activeLoaners = data.filter((l) => Number(l.amount) > 0);

      setLoaners(activeLoaners);
    });

    return () => unsubscribe();
  }, []);

  const handleDelete = async (id) => {
    const confirmDelete = window.confirm("Siz rostdan ham o’chirmoqchimisiz?");
    if (!confirmDelete) return;

    await deleteDoc(doc(db, "loaners", id));
  };

  // SEARCH FILTER
  const filteredLoaners = loaners.filter((item) =>
    item.fullName?.toLowerCase().includes(search.toLowerCase())
  );

  // EXPORT EXCEL
  const exportExcel = () => {
    const data = loaners.map((item, index) => ({
      "№": index + 1,
      "F.I.O": item.fullName,
      "Phone number": item.mainPhone,
      "Amount Loan": item.amount,
      "Deadline date": item.deadline || "",
      "Status": Number(item.amount) === 0 ? "Paid" : "Active",
    }));

    const worksheet = XLSX.utils.json_to_sheet(data);
    const workbook = XLSX.utils.book_new();

    XLSX.utils.book_append_sheet(workbook, worksheet, "Loaners");

    XLSX.writeFile(workbook, "loaners_list.xlsx");
  };

  return (
    <div>
      <div className="container mx-auto flex gap-[85px] items-center py-[22px] px-[20px] bg-[#FFFFFF] border boder-[#E5E7EB]">
        <Link to="/">
          <ArrowLeft className="cursor-pointer" />
        </Link>

        <h2 className="font-bold text-xl text-center">Qarzdorlar Ro’yxati</h2>

        {/* Excel download icon */}
        <FaFileExcel
          onClick={exportExcel}
          className="text-[24px] text-[#16A34A] cursor-pointer"
        />
      </div>

      <section className="container mx-auto px-4 mt-6">

        {/* SEARCH INPUT */}
        <input
          type="text"
          placeholder="Ism bo‘yicha qidirish..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          className="mb-4 px-4 py-2 border border-[#E5E7EB] rounded-[12px] w-full max-w-[650px] mx-auto block"
        />

        {filteredLoaners.map((item) => (
          <div
            key={item.id}
            className="bg-white border border-[#E5E7EB] rounded-[12px] p-4 mb-4 max-w-[650px] mx-auto"
          >
            <div className="flex justify-between items-center flex-wrap gap-3">
              <div className="flex gap-3 items-center">
                <span className="bg-[#DBEAFE] text-[11px] font-bold text-[#197FE6] px-3 py-2 rounded-full">
                  {item.fullName?.slice(0, 2).toUpperCase()}
                </span>

                <div>
                  <h2 className="text-[14px] font-bold">{item.fullName}</h2>
                  <p className="text-[#64748B] text-[11px]">{item.mainPhone}</p>
                </div>
              </div>

              <h2 className="text-[#197FE6] text-[14px] font-bold">
                {Number(item.amount).toLocaleString()} so’m
              </h2>
            </div>

            <div className="flex justify-between items-center mt-4 flex-wrap gap-4">
              <div className="bg-[#FFF7ED] px-4 py-2 rounded-full flex gap-5">
                <Link to={`/Addloan/${item.id}`}>
                  <FaPlusCircle className="text-[#16A34A] text-[25px]" />
                </Link>

                <Link to={`/ReducLoan/${item.id}`}>
                  <FaCircleMinus className="text-[#E11D48] text-[25px]" />
                </Link>

                <Link to={`/history/${item.id}`}>
                  <FaHistory className="text-[#808080] text-[25px]" />
                </Link>
              </div>

              <div className="bg-[#FFF7ED] px-4 py-2 rounded-full flex gap-5">
                <IoEyeSharp
                  onClick={() => setSelectedPhoto(item.photoPath)}
                  className="cursor-pointer text-[25px] text-[#F97316]"
                />

                <Link to={`/addloan/${item.id}`}>
                  <FaPencil className="text-[25px] text-[#808080]" />
                </Link>

                <RiDeleteBinLine
                  onClick={() => handleDelete(item.id)}
                  className="cursor-pointer text-[25px] text-[#E11D48]"
                />
              </div>
            </div>
          </div>
        ))}
      </section>

      {selectedPhoto && (
        <div
          onClick={() => setSelectedPhoto(null)}
          className="fixed inset-0 bg-black bg-opacity-70 flex justify-center items-center z-50"
        >
          <img
            src={selectedPhoto}
            alt=""
            className="max-w-[90%] max-h-[90%] rounded-xl"
          />
        </div>
      )}
    </div>
  );
}

